  /* ---------- Currency ---------- */
  var CUR = CONFIG.currency || { base: "USD", default: "USD", rates: { USD: 1 }, symbols: { USD: "$" }, step: { USD: 1 } };

  function convert(usd, code) {
    var rate = (CUR.rates && CUR.rates[code]) || 1;
    var step = (CUR.step && CUR.step[code]) || 1;
    var val = usd * rate;
    return Math.round(val / step) * step;
  }
  function formatPrice(usd, code) {
    code = code || CUR.default || "USD";
    var sym = (CUR.symbols && CUR.symbols[code]) || "";
    var amount = convert(usd, code).toLocaleString("en-US");
    return sym + amount;
  }

